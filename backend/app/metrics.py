import re
import time
from prometheus_client import Counter, Histogram, generate_latest, CONTENT_TYPE_LATEST


HTTP_REQUESTS = Counter(
    "cybersentinel_http_requests_total",
    "HTTP requests handled by CyberSentinel",
    ["method", "route", "status"],
)
HTTP_LATENCY = Histogram(
    "cybersentinel_http_request_duration_seconds",
    "HTTP request latency in seconds",
    ["method", "route"],
)
HTTP_ERRORS = Counter(
    "cybersentinel_http_errors_total",
    "HTTP error responses from CyberSentinel",
    ["method", "route", "status_class"],
)
SECURITY_EVENTS = Counter(
    "cybersentinel_security_events_processed_total",
    "Security events processed by the detection pipeline",
    ["event_type", "demo"],
)
INCIDENTS = Counter(
    "cybersentinel_incidents_generated_total",
    "Incidents generated by the detection engine",
    ["severity"],
)
DETECTIONS = Counter(
    "cybersentinel_threat_detections_total",
    "Threat detections generated by rule and severity",
    ["rule", "severity"],
)


def metric_route(path: str) -> str:
    """Return a bounded route label; never expose IDs, IPs, or user values."""
    if path == "/health":
        return "/health"
    if path == "/metrics":
        return "/metrics"
    if path.startswith("/api/demo/"):
        return "/api/demo/{scenario}"
    if re.fullmatch(r"/api/incidents/\d+", path):
        return "/api/incidents/{id}"
    for prefix in ("/api/stats", "/api/assets", "/api/events", "/api/incidents", "/api/reports/summary"):
        if path == prefix:
            return prefix
    return "/other"


def record_security_event(event_type: str, is_demo: bool) -> None:
    SECURITY_EVENTS.labels(event_type=event_type, demo=str(is_demo).lower()).inc()


def record_wazuh_alert() -> None:
    SECURITY_EVENTS.labels(event_type="wazuh_alert", demo="false").inc()


def record_detection(rule: str, severity: str) -> None:
    DETECTIONS.labels(rule=rule, severity=severity).inc()
    INCIDENTS.labels(severity=severity).inc()


def metrics_response():
    from fastapi.responses import Response
    return Response(generate_latest(), media_type=CONTENT_TYPE_LATEST)


async def observe_request(request, call_next):
    started = time.perf_counter()
    route = metric_route(request.url.path)
    try:
        response = await call_next(request)
    except Exception:
        HTTP_ERRORS.labels(request.method, route, "5xx").inc()
        raise
    elapsed = time.perf_counter() - started
    status = str(response.status_code)
    HTTP_REQUESTS.labels(request.method, route, status).inc()
    HTTP_LATENCY.labels(request.method, route).observe(elapsed)
    if response.status_code >= 400:
        HTTP_ERRORS.labels(request.method, route, f"{response.status_code // 100}xx").inc()
    return response
